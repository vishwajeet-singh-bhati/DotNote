import type { GeneratedNotes } from "./types";
import { formatTimestamp, buildTimestampUrl } from "./validation";

/**
 * Export generated notes as a Markdown document.
 */
export function exportAsMarkdown(notes: GeneratedNotes): string {
  const lines: string[] = [];

  // Header
  lines.push(`# ${notes.video.title}`);
  lines.push("");
  lines.push(`> Generated by LectureFlow on ${new Date(notes.generatedAt).toLocaleDateString()}`);
  if (notes.video.channel) {
    lines.push(`> Channel: ${notes.video.channel}`);
  }
  lines.push(`> Source: [${notes.video.url}](${notes.video.url})`);
  lines.push("");

  // Overview
  lines.push("## Overview");
  lines.push("");
  lines.push(notes.overview);
  lines.push("");

  // Learning Objectives
  lines.push("## Learning Objectives");
  lines.push("");
  notes.learningObjectives.forEach((obj) => {
    lines.push(`- ${obj}`);
  });
  lines.push("");

  // Detailed Notes
  lines.push("## Detailed Lecture Notes");
  lines.push("");
  lines.push(notes.detailedNotes);
  lines.push("");

  // Glossary
  if (notes.glossary.length > 0) {
    lines.push("## Keywords & Definitions");
    lines.push("");
    notes.glossary.forEach((entry) => {
      const supplementary = entry.isSupplementary ? " *(supplementary)*" : "";
      lines.push(`### ${entry.term}${supplementary}`);
      lines.push("");
      lines.push(entry.definition);
      if (entry.example) {
        lines.push("");
        lines.push(`**Example:** ${entry.example}`);
      }
      if (entry.importance) {
        lines.push("");
        lines.push(`**Importance:** ${entry.importance}`);
      }
      if (entry.sources && entry.sources.length > 0) {
        const timestamps = entry.sources
          .map((s) => `[${formatTimestamp(s.startTime)}](${buildTimestampUrl(notes.video.url, s.startTime)})`)
          .join(", ");
        lines.push("");
        lines.push(`📍 ${timestamps}`);
      }
      lines.push("");
    });
  }

  // Revision Sheet
  lines.push("## Revision Sheet");
  lines.push("");

  const rev = notes.revision;

  lines.push("### Key Takeaways");
  lines.push("");
  rev.keyTakeaways.forEach((t) => lines.push(`- ${t}`));
  lines.push("");

  lines.push("### Important Facts");
  lines.push("");
  rev.importantFacts.forEach((f) => lines.push(`- ${f}`));
  lines.push("");

  if (rev.formulasToRemember && rev.formulasToRemember.length > 0) {
    lines.push("### Formulas to Remember");
    lines.push("");
    rev.formulasToRemember.forEach((f) => lines.push(`- ${f}`));
    lines.push("");
  }

  if (rev.preconditionsAndExceptions && rev.preconditionsAndExceptions.length > 0) {
    lines.push("### Preconditions & Exceptions");
    lines.push("");
    rev.preconditionsAndExceptions.forEach((p) => lines.push(`- ${p}`));
    lines.push("");
  }

  if (rev.frequentlyConfusedConcepts && rev.frequentlyConfusedConcepts.length > 0) {
    lines.push("### Frequently Confused Concepts");
    lines.push("");
    rev.frequentlyConfusedConcepts.forEach((c) => {
      lines.push(`**${c.concepts.join(" vs ")}:** ${c.clarification}`);
      lines.push("");
    });
  }

  if (rev.practiceQuestions && rev.practiceQuestions.length > 0) {
    lines.push("### Practice Questions");
    lines.push("");
    lines.push("*These are AI-generated practice questions based on the lecture content.*");
    lines.push("");
    rev.practiceQuestions.forEach((q, i) => {
      lines.push(`**Q${i + 1}:** ${q.question}`);
      lines.push("");
      lines.push(`**A:** ${q.answer}`);
      lines.push("");
    });
  }

  if (rev.lastMinuteRevision) {
    lines.push("### Last-Minute Revision");
    lines.push("");
    lines.push(rev.lastMinuteRevision);
    lines.push("");
  }

  // Footer
  lines.push("---");
  lines.push("");
  lines.push("*Generated by LectureFlow — AI-Powered Lecture Notes*");
  lines.push(`*Source: [${notes.video.title}](${notes.video.url})*`);

  return lines.join("\n");
}
