import { describe, it, expect } from "vitest";
import { exportAsMarkdown } from "@/lib/export";
import type { GeneratedNotes } from "@/lib/types";

// ─── 11. Markdown export ────────────────────────────────────────────────────

function makeNotes(): GeneratedNotes {
  return {
    video: {
      title: "Introduction to Algorithms",
      url: "https://www.youtube.com/watch?v=testABC",
      channel: "CS Lectures",
      duration: 2700,
      thumbnail: "https://img.youtube.com/vi/testABC/default.jpg",
    },
    overview: "This lecture introduces fundamental algorithms.",
    learningObjectives: [
      "Understand sorting algorithms",
      "Analyze time complexity",
    ],
    detailedNotes:
      "## Sorting Algorithms\n\n### Quick Sort\n\nQuick sort uses divide-and-conquer...\n\n[📍 5:30](https://www.youtube.com/watch?v=testABC&t=330s)",
    mindMap: [
      { id: "root", parentId: null, label: "Algorithms" },
      { id: "t1", parentId: "root", label: "Sorting" },
    ],
    glossary: [
      {
        term: "Quick Sort",
        definition: "A divide-and-conquer sorting algorithm.",
        importance: "Commonly tested in interviews.",
        isSupplementary: false,
        sources: [{ segmentId: "seg-10", startTime: 330 }],
      },
    ],
    revision: {
      keyTakeaways: ["Quick sort has O(n log n) average case"],
      importantFacts: ["Worst case is O(n²) for sorted arrays"],
      formulasToRemember: ["T(n) = 2T(n/2) + O(n)"],
      preconditionsAndExceptions: ["Pivot choice affects performance"],
      frequentlyConfusedConcepts: [
        {
          concepts: ["Quick Sort", "Merge Sort"],
          clarification: "Quick sort is in-place; merge sort is stable.",
        },
      ],
      practiceQuestions: [
        {
          question: "What is the average time complexity of quick sort?",
          answer: "O(n log n)",
        },
      ],
      lastMinuteRevision:
        "Quick sort: divide-and-conquer, average O(n log n), in-place.",
    },
    generatedAt: "2024-01-15T10:00:00.000Z",
  };
}

describe("exportAsMarkdown", () => {
  const notes = makeNotes();
  const md = exportAsMarkdown(notes);

  it("includes the video title as heading", () => {
    expect(md).toContain("# Introduction to Algorithms");
  });

  it("includes the video URL", () => {
    expect(md).toContain("https://www.youtube.com/watch?v=testABC");
  });

  it("includes the channel", () => {
    expect(md).toContain("CS Lectures");
  });

  it("includes overview section", () => {
    expect(md).toContain("## Overview");
    expect(md).toContain("fundamental algorithms");
  });

  it("includes learning objectives", () => {
    expect(md).toContain("## Learning Objectives");
    expect(md).toContain("Understand sorting algorithms");
  });

  it("includes detailed notes", () => {
    expect(md).toContain("## Detailed Lecture Notes");
    expect(md).toContain("Quick sort uses divide-and-conquer");
  });

  it("includes glossary terms", () => {
    expect(md).toContain("## Keywords & Definitions");
    expect(md).toContain("### Quick Sort");
    expect(md).toContain("divide-and-conquer sorting algorithm");
  });

  it("includes timestamp links in glossary", () => {
    expect(md).toContain("5:30");
  });

  it("includes revision sections", () => {
    expect(md).toContain("## Revision Sheet");
    expect(md).toContain("### Key Takeaways");
    expect(md).toContain("### Important Facts");
    expect(md).toContain("### Formulas to Remember");
    expect(md).toContain("### Practice Questions");
  });

  it("marks practice questions as AI-generated", () => {
    expect(md).toContain("AI-generated practice questions");
  });

  it("includes last-minute revision", () => {
    expect(md).toContain("### Last-Minute Revision");
  });

  it("includes footer", () => {
    expect(md).toContain("Generated by LectureFlow");
  });

  it("includes frequently confused concepts", () => {
    expect(md).toContain("Quick Sort vs Merge Sort");
  });
});
